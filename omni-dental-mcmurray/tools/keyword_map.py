"""Regenerate docs/KEYWORD-MAP.md from the landing page (run from omni-dental-mcmurray/).

Usage: python3 tools/keyword_map.py
"""
import html, os, re

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
s = open(os.path.join(HERE, "emergency-dentist-mcmurray.html"), encoding="utf-8").read()
body = re.sub(r"<script.*?</script>|<style.*?</style>|<svg.*?</svg>", "", s, flags=re.S)
title = re.search(r"<title>(.*?)</title>", s).group(1)
desc = re.search(r'<meta name="description" content="([^"]+)"', s).group(1)
heads = [(m.group(1), html.unescape(re.sub(r"<[^>]+>", "", m.group(2))).strip())
         for m in re.finditer(r"<(h[1-3])[^>]*>(.*?)</\1>", body, re.S)]
text = html.unescape(re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", body.split("<body", 1)[1])))

KEYWORDS = [
    ("dental emergency", r"dental emergenc(y|ies)"),
    ("urgent dental care", r"urgent dental care"),
    ("dentist office near me now", r"dentist office near me now"),
    ("dentist near me today", r"dentist near (me|you) today"),
    ("emergency dentist near me", r"emergency dentist near (me|you)"),
    ("emergency dentist pittsburgh", r"emergency dentist (in|for) pittsburgh"),
    ("same-day emergency (supporting)", r"same-day emergency"),
    ("emergency dentist (head term)", r"emergency dentist"),
]
rows = []
for kw, pat in KEYWORDS:
    rx = re.compile(pat, re.I)
    hs = [f"{tag.upper()}: “{h}”" for tag, h in heads if rx.search(h)]
    rows.append(f"| `{kw}` | {'✓' if rx.search(title) else ''} | {'✓' if rx.search(desc) else ''} | "
                f"{'<br>'.join(hs) or '—'} | {len(rx.findall(text))} |")

md = """# Keyword Map — Omni Dental McMurray emergency LP

How each target search term is covered on `emergency-dentist-mcmurray.html`.
Generated by `tools/keyword_map.py` from the page itself (counts are exact matches or the stated
close variant in visible text; "near me" searches are matched by natural "near you" phrasing).

| Keyword | Title | Meta desc. | Headings containing it | Visible mentions |
|---|---|---|---|---|
""" + "\n".join(rows) + """

## Where the keyword content lives

- **Why section** (`#why-omni`): H2 "Your Emergency Dentist Near You in McMurray", an intro that names the
  "emergency dentist near me" / "dentist office near me now" searches, and four H3 sub-sections:
  "Need a dentist near you today?" · "Urgent dental care for every dental emergency" ·
  "Fast answers and real relief — even if you’re nervous" · "An emergency dentist for Pittsburgh’s South Hills"
- **Hero eyebrow:** "Emergency Dentist Near You · McMurray, PA"
- **Alert strip:** "Dental emergency? Same-day appointments are available in McMurray"
- **Emergencies section H2:** "Urgent Dental Care for Every Kind of Emergency"
- **Location lead:** "Easy to reach from across Pittsburgh’s South Hills…"

## Honesty guardrails

- The office is in **McMurray**, not Pittsburgh city. "Pittsburgh" is only used as "Pittsburgh’s South Hills" —
  the practice’s own wording ("Pittsburgh’s premier dental experience in the South Hills and the East End").
- "Today" / "now" phrasing never promises a time: copy says *same-day appointments* and *we make every effort to
  see you as soon as possible*. The office is closed Sat/Sun, so nothing says "open now" or "24/7"
  (only online *booking* is 24/7); evenings and weekends point to the after-hours line.

## Ads tips for these keywords

- Point *emergency dentist near me*, *dentist near me today* and *dentist office near me now* ad groups at this URL
  and use **location assets** so "near me" intent is met in the ad itself.
- For *emergency dentist pittsburgh*, target a South Hills radius rather than all of Pittsburgh, and use ad copy like
  "Emergency Dentist for Pittsburgh’s South Hills" to mirror the page.
- Schedule call assets to office hours (Liine tracking number); out-of-hours clicks land on a page that explains
  the after-hours line.
"""
open(os.path.join(HERE, "docs", "KEYWORD-MAP.md"), "w", encoding="utf-8").write(md)
print("\n".join(rows))
